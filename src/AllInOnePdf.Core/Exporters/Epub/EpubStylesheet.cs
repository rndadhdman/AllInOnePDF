using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using AllInOnePdf.Core.Documents;
using AllInOnePdf.Core.Fonts;
using AllInOnePdf.Core.Highlighting;
using AllInOnePdf.Core.Rendering;
using AllInOnePdf.Core.Themes;
using ThemeFontWeight = AllInOnePdf.Core.Themes.FontWeight;

namespace AllInOnePdf.Core.Exporters.Epub;

/// <summary>One embedded font file as the stylesheet references it.</summary>
internal sealed record EpubFontFace(string Family, string Href, int Weight, bool Italic);

/// <summary>
/// Turns a <see cref="PdfTheme"/> into an EPUB stylesheet for the <c>aio-*</c> markup of <see cref="DocumentHtmlRenderer"/>.
/// Mirrors the theme builder's CSS mapping, but sizes are relative (11 pt body = 1 em) so the reader's font-size
/// setting still works, page geometry is left to the reader, and — when <c>respectReaderTheme</c> is on — no fixed
/// text or background colours are set, so night and sepia modes stay readable. Every theme value is validated before
/// it reaches the CSS (themes are imported from untrusted JSON).
/// </summary>
internal static partial class EpubStylesheet
{
    private const double ReaderBasePt = 11;
    private const string Tint = "rgba(128,128,128,0.12)";
    private const string TintStrong = "rgba(128,128,128,0.2)";
    private const string TintBorder = "rgba(128,128,128,0.4)";

    public static string Build(PdfTheme t, EpubSettings settings, IReadOnlyList<EpubFontFace> fonts)
    {
        var css = new StringBuilder(12288);
        var fixedColors = !settings.RespectReaderTheme;
        void Rule(string selector, string declarations) => css.Append(selector).Append(" {").Append(declarations).Append("}\n");

        var text = Color(t.Colors.Text, "#1F2937");
        var muted = Color(t.Colors.Muted, "#6B7280");
        var accent = Color(t.Colors.Accent, "#0F6CBD");
        var surface = Color(t.Colors.Surface, "#F3F4F6");
        var border = Color(t.Colors.Border, "#D1D5DB");
        var pageBg = Color(t.Page.Background, "#FFFFFF");
        var body = Positive(t.Typography.BodySizePt, ReaderBasePt);
        var sp = Math.Max(0, t.Typography.ParagraphSpacingPt);
        var bodyFont = FontStack(t.Typography.BodyFont);
        var headingFont = FontStack(t.Headings.Font ?? t.Typography.BodyFont);
        var mono = FontStack(t.Code.Font, monoFallback: true);
        var headingColor = Color(t.Headings.Color, "#111827");
        var mutedDecl = fixedColors ? $"color:{muted};" : "opacity:0.75;";

        css.Append("/* Generated by AllInOne PDF from the \"").Append(SafeComment(t.Name)).Append("\" theme. */\n");
        css.Append("@namespace epub \"http://www.idpf.org/2007/ops\";\n");
        foreach (var face in fonts)
        {
            Rule("@font-face", $"font-family:\"{SafeFontName(face.Family)}\";src:url(\"{face.Href}\") format(\"truetype\");font-weight:{face.Weight.ToString(CultureInfo.InvariantCulture)};font-style:{(face.Italic ? "italic" : "normal")};");
        }

        // ---- body text
        var bodyDecl = new StringBuilder();
        bodyDecl.Append(CultureInfo.InvariantCulture, $"font-family:{bodyFont};font-size:{Em(body, ReaderBasePt)};line-height:{N(Positive(t.Typography.LineHeight, 1.5))};");
        if (t.Typography.LetterSpacingEm != 0)
        {
            bodyDecl.Append(CultureInfo.InvariantCulture, $"letter-spacing:{N(t.Typography.LetterSpacingEm)}em;");
        }

        // A dark theme's text colours only work on its own page colour, so fixed-colour mode brings the page along.
        var applyBackground = settings.ApplyPageBackground || (fixedColors && IsDark(t.Page.Background));
        if (fixedColors)
        {
            bodyDecl.Append(CultureInfo.InvariantCulture, $"color:{text};");
        }

        if (applyBackground)
        {
            bodyDecl.Append(CultureInfo.InvariantCulture, $"background-color:{pageBg};");
            if (!fixedColors)
            {
                bodyDecl.Append(CultureInfo.InvariantCulture, $"color:{text};");
            }
        }

        Rule("body", bodyDecl.ToString());
        Rule(".aio-doc", "margin:0;padding:0;");
        Rule("strong", "font-weight:700;");
        Rule(".aio-smallcaps", "font-variant:small-caps;");
        Rule("mark", fixedColors ? $"background-color:{(IsDark(t.Page.Background) ? "#5C4B00" : "#FFF3A0")};color:inherit;" : "background-color:rgba(255,214,0,0.35);color:inherit;");
        Rule("sup, sub", "line-height:0;");

        // ---- paragraphs
        var align = Html.ThemeStylesheet.CssAlign(t.Typography.Alignment);
        var hyphens = t.Typography.Hyphenate ? "auto" : "manual";
        Rule("p.aio-p", $"margin:0 0 {Em(sp, body)};text-indent:0;text-align:{align};-webkit-hyphens:{hyphens};-epub-hyphens:{hyphens};hyphens:{hyphens};orphans:2;widows:2;");
        if (t.Typography.FirstLineIndentPt > 0)
        {
            Rule(".aio-doc > p.aio-p", $"text-indent:{Em(t.Typography.FirstLineIndentPt, body)};");
        }

        Rule("li p.aio-p, blockquote p.aio-p, aside p.aio-p, td p.aio-p, th p.aio-p", $"margin-bottom:{Em(Math.Min(sp, 4), body)};text-indent:0;");

        // ---- headings
        Rule(".aio-h", $"font-family:{headingFont};line-height:{N(Positive(t.Headings.LineHeight, 1.2))};{(fixedColors ? "color:" + headingColor + ";" : string.Empty)}text-indent:0;text-align:left;page-break-after:avoid;break-after:avoid;page-break-inside:avoid;break-inside:avoid;-webkit-hyphens:manual;hyphens:manual;");
        for (var level = 1; level <= 6; level++)
        {
            var h = t.Headings.Level(level);
            var size = Positive(h.SizePt, body);
            var decl = new StringBuilder();
            decl.Append(CultureInfo.InvariantCulture, $"font-size:{Em(size, body)};font-weight:{Weight(h.Weight)};font-style:{(h.Italic ? "italic" : "normal")};");
            decl.Append(CultureInfo.InvariantCulture, $"text-transform:{(h.Uppercase ? "uppercase" : "none")};letter-spacing:{N(h.LetterSpacingEm)}em;");
            decl.Append(CultureInfo.InvariantCulture, $"margin:{Em(Math.Max(0, h.SpaceBeforePt), size)} 0 {Em(Math.Max(0, h.SpaceAfterPt), size)};text-align:{Html.ThemeStylesheet.CssAlign(h.Alignment, headings: true)};");
            if (fixedColors && !string.IsNullOrWhiteSpace(h.Color))
            {
                decl.Append(CultureInfo.InvariantCulture, $"color:{Color(h.Color, headingColor)};");
            }

            if (h.Underline)
            {
                decl.Append(CultureInfo.InvariantCulture, $"border-bottom:{N(Math.Max(0.25, h.RuleWidthPt))}pt solid {Color(h.RuleColor, accent)};padding-bottom:0.15em;");
            }

            if (t.Headings.NumberHeadings)
            {
                decl.Append(CultureInfo.InvariantCulture, $"counter-increment:aioh{level};");
                if (level < 6)
                {
                    decl.Append("counter-reset:").Append(string.Join(' ', Enumerable.Range(level + 1, 6 - level).Select(l => "aioh" + l.ToString(CultureInfo.InvariantCulture)))).Append(';');
                }
            }

            Rule("h" + level.ToString(CultureInfo.InvariantCulture) + ".aio-h", decl.ToString());
            if (t.Headings.NumberHeadings)
            {
                var counters = string.Join(" \".\" ", Enumerable.Range(1, level).Select(l => $"counter(aioh{l.ToString(CultureInfo.InvariantCulture)})"));
                Rule("h" + level.ToString(CultureInfo.InvariantCulture) + ".aio-h::before", $"content:{counters} \"\\00a0\\00a0\";{(fixedColors ? "color:" + accent + ";" : string.Empty)}");
            }
        }

        // ---- links and note references
        var linkColor = Color(t.Links.Color, accent);
        Rule("a", "color:inherit;");
        Rule("a.aio-link", $"color:{linkColor};text-decoration:{(t.Links.Underline ? "underline" : "none")};font-weight:{Weight(t.Links.Weight)};");
        if (t.Links.ShowUrl)
        {
            Rule("a.aio-link[href^=\"http:\"]::after, a.aio-link[href^=\"https:\"]::after, a.aio-link[href^=\"mailto:\"]::after", $"content:\" (\" attr(href) \")\";font-size:0.85em;font-weight:400;{mutedDecl}");
        }

        Rule(".aio-fnref a, a[epub|type~=\"noteref\"]", $"color:{accent};text-decoration:none;");

        // ---- inline code and math
        var c = t.Code;
        var codeSize = Positive(c.SizePt, body * 0.86);
        var codeBg = Color(c.Background, surface);
        var codeFg = Color(c.TextColor, text);
        var inlineBg = Color(c.InlineBackground ?? c.Background, surface);
        var inlineFg = c.InlineTextColor is not null || c.TextColor is not null ? Color(c.InlineTextColor ?? c.TextColor, text) : "inherit";
        Rule("code.aio-code", $"font-family:{mono};font-size:{N(Positive(c.InlineScale, 0.9))}em;padding:0 0.15em;border-radius:0.2em;{(fixedColors ? $"background-color:{inlineBg};color:{inlineFg};" : $"background-color:{Tint};")}");
        Rule("code.aio-math-inline", $"font-family:{mono};font-size:0.95em;");
        Rule("pre.aio-math", $"margin:0 0 {Em(sp, body)};padding:0;text-align:center;font-family:{mono};font-size:{Em(codeSize, body)};white-space:pre-wrap;");
        Rule("pre.aio-math code", "font:inherit;");

        // ---- code blocks
        Rule("figure", "margin:0;padding:0;");
        Rule("figure.aio-codeblock", $"margin:0 0 {Em(Math.Max(sp, 6), body)};");
        var codeBorder = c.BorderWidthPt > 0 ? $"{N(c.BorderWidthPt)}pt solid {(fixedColors ? Color(c.BorderColor, border) : TintBorder)}" : "none";
        Rule("figure.aio-codeblock pre", $"margin:0;font-family:{mono};font-size:{Em(codeSize, body)};line-height:{N(Positive(c.LineHeight, 1.45))};" +
            $"padding:{Em(Math.Max(0, c.PaddingPt), codeSize)};border:{codeBorder};border-radius:{N(Math.Max(0, c.CornerRadiusPt))}pt;text-align:left;text-indent:0;" +
            (fixedColors ? $"background-color:{codeBg};color:{codeFg};" : $"background-color:{Tint};") +
            (c.WrapLongLines ? "white-space:pre-wrap;word-wrap:break-word;overflow-wrap:break-word;" : "white-space:pre;overflow-x:auto;") +
            "-webkit-hyphens:none;hyphens:none;");
        Rule("figure.aio-codeblock pre code", "font:inherit;color:inherit;background:none;padding:0;");
        Rule("figure.aio-codeblock figcaption", c.ShowLanguageLabel
            ? $"display:block;font-family:{mono};font-size:{Em(codeSize * 0.9, body)};margin:0 0 0.2em;line-height:1.3;{mutedDecl}"
            : "display:none;");

        var codeIsDark = IsDark(c.Background ?? t.Colors.Surface);
        if (fixedColors)
        {
            AppendHighlight(css, string.Empty, SyntaxHighlighter.ResolvePalette(c.Palette, codeIsDark));
        }
        else
        {
            AppendHighlight(css, string.Empty, c.Palette == SyntaxPalette.Mono ? SyntaxPalette.Mono : SyntaxPalette.Light);
        }

        // ---- quotes
        var q = t.Quotes;
        var quoteBorder = q.BorderWidthPt > 0 ? $"{N(q.BorderWidthPt)}pt solid {Color(q.BorderColor, accent)}" : "none";
        var quotePad = Math.Max(0, q.PaddingPt);
        Rule("blockquote.aio-quote", $"margin:0 0 {Em(sp, body)};border-left:{quoteBorder};padding:{Em(quotePad * 0.5, body)} {Em(quotePad * 0.5, body)} {Em(quotePad * 0.5, body)} {Em(quotePad, body)};" +
            $"font-style:{(q.Italic ? "italic" : "normal")};font-size:{N(Positive(q.FontScale, 1))}em;" +
            (fixedColors ? $"color:{Color(q.TextColor, text)};{(string.IsNullOrWhiteSpace(q.Background) ? string.Empty : "background-color:" + Color(q.Background, surface) + ";")}" : string.Empty));
        Rule("blockquote.aio-quote .aio-attribution", $"display:block;font-style:normal;font-size:0.9em;margin-top:0.2em;{mutedDecl}");
        Rule("blockquote.aio-quote .aio-attribution::before", "content:\"\\2014\\00a0\";");

        // ---- callouts
        var co = t.Callouts;
        Rule("aside.aio-callout", $"display:block;margin:0 0 {Em(Math.Max(sp, 6), body)};padding:{Em(Math.Max(0, co.PaddingPt), body)};border-radius:{N(Math.Max(0, co.CornerRadiusPt))}pt;page-break-inside:avoid;break-inside:avoid;");
        foreach (var kind in Enum.GetValues<CalloutKind>())
        {
            var style = co.Kind(kind);
            var kindAccent = Color(style.Accent, accent);
            var bar = co.BorderWidthPt > 0 ? $"border-left:{N(co.BorderWidthPt)}pt solid {kindAccent};" : "border-left:0;";
            var bg = fixedColors ? Color(style.Background ?? co.Background, surface) : Alpha(style.Accent ?? t.Colors.Accent, 0.08) ?? Tint;
            var cls = "aside.aio-callout-" + kind.ToString().ToLowerInvariant();
            Rule(cls, $"background-color:{bg};{bar}");
            Rule(cls + " > .aio-callout-title", $"color:{kindAccent};");
        }

        Rule(".aio-callout-title", co.ShowLabel
            ? "font-weight:600;font-size:0.95em;line-height:1.2;margin:0 0 0.3em;text-indent:0;"
            : "display:none;");

        // ---- lists
        var l = t.Lists;
        var marker = Color(l.MarkerColor, accent);
        Rule(".aio-list", $"margin:0 0 {Em(sp, body)};padding:0 0 0 {Em(Math.Max(6, l.IndentPt), body)};");
        Rule(".aio-list .aio-list", "margin-bottom:0.15em;");
        Rule(".aio-list > li", "margin:0;");
        Rule(".aio-list > li + li", $"margin-top:{Em(Math.Max(0, l.ItemSpacingPt), body)};");
        var (bulletKeyword, bulletString) = Bullet(l.Bullet);
        Rule("ul.aio-list", bulletString is null ? $"list-style-type:{bulletKeyword};" : $"list-style-type:{bulletKeyword};list-style-type:\"{bulletString}\\00a0\";");
        Rule("ol.aio-list", $"list-style-type:{NumberStyleCss(l.Numbering)};");
        Rule(".aio-list > li::marker", $"color:{marker};");
        Rule("li.aio-task", "list-style-type:none;list-style:none;");
        Rule(".aio-task-box", l.TaskCheckboxes
            ? $"display:inline-block;width:1.3em;margin-left:-1.3em;color:{marker};font-style:normal;"
            : "display:none;");

        // ---- tables
        var tb = t.Tables;
        var tBorder = fixedColors ? Color(tb.BorderColor, border) : (tb.BorderColor is null ? TintBorder : Color(tb.BorderColor, border));
        var bw = Math.Max(0.25, tb.BorderWidthPt);
        var tableSize = Positive(tb.FontScale, 0.92);
        string? headerBg = fixedColors
            ? (tb.HeaderBackground is not null ? Color(tb.HeaderBackground, surface) : tb.Style is TableStyle.Grid or TableStyle.Striped ? surface : null)
            : (tb.HeaderBackground is not null || tb.Style is TableStyle.Grid or TableStyle.Striped ? Tint : null);
        Rule("figure.aio-tablewrap", $"margin:0 0 {Em(Math.Max(sp, 6), body)};overflow-x:auto;");
        Rule("table.aio-table", $"width:100%;border-collapse:collapse;border-spacing:0;font-size:{N(tableSize)}em;line-height:1.3;");
        Rule("table.aio-table caption", tb.ShowCaptions ? $"caption-side:top;text-align:left;font-style:italic;font-size:0.95em;padding:0 0 0.3em;{mutedDecl}" : "display:none;");
        Rule("table.aio-table th, table.aio-table td", $"padding:{Em(Math.Max(0, tb.CellPaddingPt), body * tableSize)};vertical-align:top;text-align:left;border:0;");
        Rule("table.aio-table th", $"font-weight:{Weight(tb.HeaderWeight)};{(fixedColors ? "color:" + Color(tb.HeaderTextColor, text) + ";" : string.Empty)}{(headerBg is null ? string.Empty : "background-color:" + headerBg + ";")}");
        switch (tb.Style)
        {
            case TableStyle.Grid:
                Rule("table.aio-table th, table.aio-table td", $"border:{N(bw)}pt solid {tBorder};");
                break;
            case TableStyle.Lines:
                Rule("table.aio-table th", $"border-bottom:{N(bw * 1.6)}pt solid {tBorder};");
                Rule("table.aio-table td", $"border-bottom:{N(bw)}pt solid {tBorder};");
                break;
            case TableStyle.Minimal:
                Rule("table.aio-table th", $"border-bottom:{N(bw * 1.6)}pt solid {tBorder};");
                break;
            case TableStyle.Striped:
                Rule("table.aio-table th", $"border-bottom:{N(bw * 1.6)}pt solid {tBorder};");
                Rule("table.aio-table tbody tr:nth-child(even) td", $"background-color:{(fixedColors ? Color(tb.StripeColor, surface) : Tint)};");
                break;
        }

        // ---- images
        var im = t.Images;
        var imgAlign = im.Align switch { ImageAlign.Left => "left", ImageAlign.Right => "right", _ => "center" };
        Rule("figure.aio-figure", $"margin:0 0 {Em(Math.Max(0, im.SpacingPt), body)};text-align:{imgAlign};text-indent:0;page-break-inside:avoid;break-inside:avoid;");
        Rule("figure.aio-figure img", $"max-width:{N(Math.Clamp(im.MaxWidthPercent, 5, 100))}%;height:auto;border-radius:{N(Math.Max(0, im.CornerRadiusPt))}pt;border:{(im.Border ? "0.75pt solid " + (fixedColors ? border : TintBorder) : "0")};");
        Rule("figure.aio-figure figcaption", im.ShowCaptions
            ? $"display:block;font-size:{Em(Positive(im.CaptionSizePt, 9), body)};font-style:italic;margin:0;padding-top:0.3em;text-align:{imgAlign};{mutedDecl}"
            : "display:none;");
        Rule(".aio-image-missing", $"display:block;padding:0.8em;font-style:italic;text-align:center;border:1px dashed {(fixedColors ? border : TintBorder)};{mutedDecl}");
        Rule("img.aio-inline-img", "height:1.2em;width:auto;vertical-align:middle;");

        // ---- rules, breaks, footnotes
        Rule("hr.aio-hr", $"border:0;border-top:1px solid {(fixedColors ? border : TintBorder)};height:0;margin:{Em(Math.Max(6, sp), body)} 0;");
        Rule(".aio-pagebreak", "height:0;margin:0;padding:0;page-break-after:always;break-after:page;");
        Rule("section.aio-footnotes", $"margin-top:2em;padding-top:0.5em;border-top:1px solid {(fixedColors ? border : TintBorder)};font-size:0.85em;");
        Rule("aside.aio-footnote", "display:block;margin:0 0 0.5em;");
        Rule("aside.aio-footnote p.aio-p", "margin:0 0 0.3em;text-indent:0;text-align:left;");
        Rule("a.aio-fn-back", $"text-decoration:none;font-weight:600;color:{accent};");

        // ---- cover / title page
        var cv = t.Cover;
        var coverAlign = cv.Style is CoverStyle.Minimal or CoverStyle.Split ? "left" : "center";
        var titleSize = Math.Clamp(Positive(cv.TitleSizePt, 40), body, body * 3.5);
        Rule("section.aio-cover", $"text-align:{coverAlign};margin-top:{(cv.Style == CoverStyle.Bold ? "45%" : "25%")};{(cv.Style == CoverStyle.Split ? $"border-left:0.5em solid {accent};padding-left:1em;" : string.Empty)}");
        Rule(".aio-cover-accent", $"display:block;width:4em;height:0;border-top:0.3em solid {accent};margin:0 {(coverAlign == "center" ? "auto" : "0")} 1em;");
        Rule("h1.aio-cover-title", $"font-family:{headingFont};font-size:{Em(titleSize, body)};font-weight:700;line-height:1.1;margin:0 0 0.3em;text-align:{coverAlign};{(fixedColors ? "color:" + Color(cv.TitleColor, headingColor) + ";" : string.Empty)}page-break-after:avoid;");
        Rule("p.aio-cover-subtitle", $"font-family:{headingFont};font-size:{Em(titleSize * 0.45, body)};line-height:1.25;margin:0 0 1.5em;text-align:{coverAlign};{mutedDecl}");
        Rule("p.aio-cover-author", $"font-size:1.05em;margin:0 0 0.3em;text-align:{coverAlign};text-indent:0;");
        Rule("p.aio-cover-date", $"font-size:0.95em;margin:0 0 0.3em;text-align:{coverAlign};text-indent:0;{mutedDecl}");
        Rule("p.aio-cover-note", $"font-size:0.9em;font-style:italic;margin:1em 0 0;text-align:{coverAlign};text-indent:0;{mutedDecl}");

        // ---- navigation document
        Rule("nav#toc ol, nav.aio-nav ol", "list-style-type:none;list-style:none;margin:0;padding:0 0 0 1.2em;");
        Rule("nav#toc > ol", "padding-left:0;");
        Rule("nav#toc li", "margin:0.25em 0;");
        Rule("nav#toc a", "text-decoration:none;");
        Rule("h1.aio-nav-title", $"font-family:{headingFont};font-size:{Em(Positive(t.Headings.H1.SizePt, 24) * 0.8, body)};margin:0 0 0.6em;");

        if (!fixedColors)
        {
            // Readers that report a dark preference (or apply their own night mode) keep the text colour; the few
            // accent colours left in the sheet are lifted so they stay readable on a dark page.
            css.Append("@media (prefers-color-scheme: dark) {\n");
            Rule("a.aio-link", "color:inherit;text-decoration:underline;");
            Rule(".aio-callout-title, aside.aio-callout > .aio-callout-title, .aio-fnref a, a.aio-fn-back", "color:inherit;");
            Rule("mark", "background-color:rgba(255,214,0,0.3);color:inherit;");
            AppendHighlight(css, string.Empty, c.Palette == SyntaxPalette.Mono ? SyntaxPalette.Mono : SyntaxPalette.Dark);
            css.Append("}\n");
        }

        return css.ToString();
    }

    private static void AppendHighlight(StringBuilder css, string prefix, SyntaxPalette palette)
    {
        foreach (var kind in Enum.GetValues<SyntaxTokenKind>())
        {
            var cls = SyntaxTokenKinds.CssClass(kind);
            if (cls is null)
            {
                continue;
            }

            var decl = new StringBuilder();
            var color = SyntaxHighlighter.ColorFor(kind, palette, darkBackground: palette == SyntaxPalette.Dark);
            decl.Append(color is null ? "color:inherit;" : $"color:{Color(color, "#000000")};");
            var bold = palette == SyntaxPalette.Mono && kind is SyntaxTokenKind.Keyword or SyntaxTokenKind.Inserted;
            var italic = kind == SyntaxTokenKind.Comment || (palette == SyntaxPalette.Mono && kind == SyntaxTokenKind.Deleted);
            decl.Append(bold ? "font-weight:700;" : string.Empty).Append(italic ? "font-style:italic;" : string.Empty);
            css.Append(prefix).Append(".hl-").Append(cls).Append(" {").Append(decl).Append("}\n");
        }
    }

    /// <summary>Quoted CSS font stack naming the theme font, then the bundled fallback, then a generic family.</summary>
    public static string FontStack(string? family, bool monoFallback = false)
    {
        var name = SafeFontName(family);
        if (string.IsNullOrEmpty(name))
        {
            name = monoFallback ? BundledFonts.Mono : BundledFonts.Sans;
        }

        var cls = BundledFonts.Families.FirstOrDefault(f => string.Equals(f.Name, name, StringComparison.OrdinalIgnoreCase))?.Class
                  ?? (monoFallback ? FontClass.Mono : FontClass.Sans);
        var generic = cls switch { FontClass.Serif => "serif", FontClass.Mono => "monospace", _ => "sans-serif" };
        return $"\"{name}\",{generic}";
    }

    public static string SafeFontName(string? family) =>
        family is null ? string.Empty : FontNameStrip().Replace(family, string.Empty).Trim();

    private static string SafeComment(string? text) => FontNameStrip().Replace(text ?? string.Empty, string.Empty);

    private static string Weight(ThemeFontWeight w) => w switch
    {
        ThemeFontWeight.Medium => "500",
        ThemeFontWeight.SemiBold => "600",
        ThemeFontWeight.Bold => "700",
        _ => "400",
    };

    private static string N(double value) => Math.Round(double.IsFinite(value) ? value : 0, 3).ToString("0.###", CultureInfo.InvariantCulture);

    /// <summary>A length in points expressed relative to the element's own font size.</summary>
    private static string Em(double pt, double basePt) => pt == 0 ? "0" : N(pt / Positive(basePt, ReaderBasePt)) + "em";

    private static double Positive(double value, double fallback) => double.IsFinite(value) && value > 0 ? value : fallback;

    private static (string Keyword, string? Text) Bullet(BulletStyle style) => style switch
    {
        BulletStyle.Circle => ("circle", null),
        BulletStyle.Square => ("square", null),
        BulletStyle.Dash => ("disc", "\\2013"),
        BulletStyle.Arrow => ("disc", "\\203A"),
        _ => ("disc", null),
    };

    private static string NumberStyleCss(NumberStyle style) => style switch
    {
        NumberStyle.LowerAlpha => "lower-alpha",
        NumberStyle.UpperAlpha => "upper-alpha",
        NumberStyle.LowerRoman => "lower-roman",
        NumberStyle.UpperRoman => "upper-roman",
        _ => "decimal",
    };

    /// <summary>A validated CSS colour (#RRGGBB, or rgba() for theme colours with alpha); falls back when invalid.</summary>
    public static string Color(string? hex, string fallback)
    {
        if (TryParse(hex, out var r, out var g, out var b, out var a) || TryParse(fallback, out r, out g, out b, out a))
        {
            return a >= 255
                ? string.Create(CultureInfo.InvariantCulture, $"#{r:X2}{g:X2}{b:X2}")
                : string.Create(CultureInfo.InvariantCulture, $"rgba({r},{g},{b},{N(a / 255.0)})");
        }

        return "#000000";
    }

    private static string? Alpha(string? hex, double alpha) =>
        TryParse(hex, out var r, out var g, out var b, out _)
            ? string.Create(CultureInfo.InvariantCulture, $"rgba({r},{g},{b},{N(alpha)})")
            : null;

    public static bool IsDark(string? hex)
    {
        if (!TryParse(hex, out var r, out var g, out var b, out _))
        {
            return false;
        }

        var luminance = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255.0;
        return luminance < 0.5;
    }

    /// <summary>Parses #RGB, #RRGGBB and the theme's #AARRGGBB form.</summary>
    private static bool TryParse(string? hex, out int r, out int g, out int b, out int a)
    {
        r = g = b = 0;
        a = 255;
        if (string.IsNullOrWhiteSpace(hex))
        {
            return false;
        }

        var s = hex.Trim();
        if (s[0] != '#' || !HexDigits().IsMatch(s[1..]))
        {
            return false;
        }

        s = s[1..];
        if (s.Length == 3)
        {
            s = string.Concat(s.Select(ch => new string(ch, 2)));
        }

        if (s.Length == 8)
        {
            a = Convert.ToInt32(s[..2], 16);
            s = s[2..];
        }

        if (s.Length != 6)
        {
            return false;
        }

        r = Convert.ToInt32(s[..2], 16);
        g = Convert.ToInt32(s[2..4], 16);
        b = Convert.ToInt32(s[4..], 16);
        return true;
    }

